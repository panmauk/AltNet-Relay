#!/usr/bin/env bash
# Builds AltNet Relay for Windows: the desktop app, then its installer.
#
#   scripts/build-windows.sh
#
# Output goes to dist/. Everything is built offline (GOPROXY=off): Relay
# is stdlib-only and the Wails module is already in the local cache, so a
# build that suddenly wants the network means something changed that
# should be looked at, not silently downloaded.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
fail() { echo "build-windows: $*" >&2; exit 1; }

command -v wails >/dev/null 2>&1 ||
    fail "wails not found on PATH (install with: go install github.com/wailsapp/wails/v2/cmd/wails@v2.12.0)"

# Find the Inno Setup compiler: PATH first, then the usual install dirs.
iscc="$(command -v iscc 2>/dev/null || true)"
if [ -z "$iscc" ]; then
    for candidate in \
        "/c/Program Files (x86)/Inno Setup 6/ISCC.exe" \
        "/c/Program Files/Inno Setup 6/ISCC.exe" \
        "$LOCALAPPDATA/Programs/Inno Setup 6/ISCC.exe"; do
        if [ -f "$candidate" ]; then iscc="$candidate"; break; fi
    done
fi
[ -n "$iscc" ] || fail "Inno Setup compiler (ISCC.exe) not found -- install Inno Setup 6"

# The icon is a checked-in build input (generated by scripts/make-icons.go),
# so a missing one is an error rather than something to paper over: Wails
# would silently substitute its own default logo.
[ -f "$root/app/desktop/build/windows/icon.ico" ] ||
    fail "app/desktop/build/windows/icon.ico missing -- run: go run scripts/make-icons.go"

echo "==> building AltNetRelay.exe"
# No -clean: it would delete build/bin, and there is nothing stale there
# worth the risk of a future Wails version cleaning more than that.
(cd "$root/app/desktop" && GOPROXY=off wails build -s -trimpath)

exe="$root/app/desktop/build/bin/AltNetRelay.exe"
[ -f "$exe" ] || fail "wails reported success but $exe is missing"

mkdir -p "$root/dist"
cp "$exe" "$root/dist/"

echo "==> building installer"
# MSYS would rewrite ISCC's /Q switch into a Windows path, so path
# conversion is switched off and the script path converted explicitly.
MSYS_NO_PATHCONV=1 "$iscc" /Q "$(cygpath -w "$root/scripts/AltNetRelay.iss")"

echo
echo "==> done"
ls -la "$root/dist"
